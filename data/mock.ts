const allActions: PermissionAction[] = [
  "view",
  "create",
  "edit",
  "delete",
  "approve",
  "export",
];

function actions(
  enabled: PermissionAction[],
): Record<PermissionAction, boolean> {
  return Object.fromEntries(
    allActions.map((action) => [action, enabled.includes(action)]),
  ) as Record<PermissionAction, boolean>;
}

function policy(
  roleId: string,
  matrix: Record<string, PermissionAction[]>,
  visibility: PermissionPolicy["visibility"],
  locationScope: PermissionPolicy["locationScope"] = "all",
): PermissionPolicy {
  return {
    roleId,
    modules: moduleDefinitions.map((module) => ({
      moduleId: module.id,
      actions: actions(matrix[module.id] ?? []),
    })),
    visibility,
    locationScope,
    selectedLocationIds: locationScope === "all" ? [] : ["loc-harwin"],
    updatedAt: "Today, 9:42 AM",
  };
}

